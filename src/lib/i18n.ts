const DICTS: Record<Lang, Dict> = { th, zh, en, ja }

export type TKey = keyof Dict
export type T = (key: TKey, vars?: Record<string, string | number>) => string

export function translator(lang: Lang): T {
  const dict = DICTS[lang] ?? en
  return (key, vars) => {
    let s = dict[key] ?? en[key]
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
    return s
  }
}

export function formatDuration(t: T, totalMin: number) {
  const h = Math.floor(totalMin / 60)
  const m = totalMin % 60
  if (h === 0) return t("minutes", { m })
  return m === 0 ? t("hours", { h }) : `${t("hours", { h })} ${t("minutes", { m })}`
}
