export type Lang = "th" | "zh" | "en" | "ja"

export const LANGS: { id: Lang; label: string; dateLocale: string }[] = [
  { id: "th", label: "ไทย", dateLocale: "th-TH" },
  { id: "zh", label: "中文", dateLocale: "zh-CN" },
  { id: "en", label: "English", dateLocale: "en-GB" },
  { id: "ja", label: "日本語", dateLocale: "ja-JP" },
]

export function dateLocale(lang: Lang) {
  return LANGS.find((l) => l.id === lang)?.dateLocale ?? "en-GB"
}

export function detectLang(): Lang {
  try {
    const nav = navigator.language.toLowerCase()
    if (nav.startsWith("th")) return "th"
    if (nav.startsWith("zh")) return "zh"
    if (nav.startsWith("ja")) return "ja"
    if (nav.startsWith("en")) return "en"
  } catch {}
  return "th"
}

